package app.tuti.tj.data.auth

// ════════════════════════════════════════════════════════════════
//  ПРИВЯЗКА АККАУНТА — РЕЗУЛЬТАТ И ВИДЫ ОТКАЗОВ
//
//  Отмена стоит отдельно от ошибок намеренно. Человек, закрывший
//  окно выбора аккаунта, ничего не сломал — показывать ему красный
//  текст не за что. Смешай их в одном типе, и на экране рано или
//  поздно появится ошибка там, где её быть не должно.
// ════════════════════════════════════════════════════════════════

enum class AuthErrorKind {
    /** Нет интернета. */
    NO_NETWORK,

    /** Google Play Services недоступны или устарели. */
    PLAY_SERVICES,

    /** Аккаунт уже привязан к другому профилю — прогресс будем восстанавливать. */
    ACCOUNT_CONFLICT,

    /** Всё остальное: показываем общий текст и даём связаться с нами. */
    UNKNOWN,
}

sealed interface AccountLinkResult {
    data object Success : AccountLinkResult

    /** Пользователь закрыл окно выбора аккаунта. Не ошибка. */
    data object Cancelled : AccountLinkResult

    data class Failure(val kind: AuthErrorKind) : AccountLinkResult
}
